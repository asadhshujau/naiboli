// Generates src/ui/icons.generated.ts from @material-symbols/svg-400 (Rounded, weight 400).
// Each icon gets its outline (FILL 0) and filled (FILL 1) path, rendered by <Icon> via react-native-svg.
// Usage: node scripts/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'node_modules/@material-symbols/svg-400/rounded');

// Every icon name the app can render (markup + dynamic names in the prototype script).
const NAMES = `air arrow_forward beach_access bedtime chevron_left chevron_right close cloud cloud_off directions_boat
directions_boat_filled directions_bus directions_walk expand_more explore flight flight_takeoff foggy footprint hourglass_top
humidity_percentage kayaking kitesurfing landscape light_mode lightbulb local_taxi location_disabled location_off location_on
map more_horiz my_location navigation near_me north_east open_in_new partly_cloudy_day partly_cloudy_night phishing pool radar
rainy replay route rowing sailing scuba_diving search south_east speed sunny surfing swap_horiz thermostat thunderstorm umbrella
visibility warning water waves wb_sunny wb_twilight weather_snowy wrong_location`
  .split(/\s+/)
  .filter(Boolean);

// Web-font ligature aliases → file names in the SVG package. `fill: true` = always the filled glyph.
const ALIAS = {
  expand_more: { file: 'keyboard_arrow_down' },
  directions_boat_filled: { file: 'directions_boat', fill: true },
};

const pathOf = (file) => {
  const svg = fs.readFileSync(path.join(dir, file + '.svg'), 'utf8');
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${file}: unexpected viewBox`);
  const ds = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (ds.length !== 1) throw new Error(`${file}: expected one path, got ${ds.length}`);
  return ds[0];
};

let out = `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Rounded). Do not edit.\n`;
out += `// viewBox "0 -960 960 960"; [outline (FILL 0), filled (FILL 1)].\n\n`;
out += `export const ICON_PATHS = {\n`;
for (const name of [...new Set(NAMES)].sort()) {
  const a = ALIAS[name] ?? { file: name };
  const filled = pathOf(a.file + '-fill');
  const outline = a.fill ? filled : pathOf(a.file);
  out += `  ${name}: [${JSON.stringify(outline)}, ${JSON.stringify(filled)}],\n`;
}
out += `} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`;
const target = path.join(root, 'src/ui/icons.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${NAMES.length} icons, ${(out.length / 1024).toFixed(0)} KB → ${path.relative(root, target)}`);
